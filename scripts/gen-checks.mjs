// Embed apps/pages/static/checks.json into the web app as a generated TS
// module, keyed by page id (the html filename minus ".html").
//
// Why embed rather than fetch at runtime: the review screen needs this data
// in the *teacher app* (localhost:5173 / the `web` container), but
// checks.json lives under apps/pages/static, which is only bind-mounted into
// the `pages` nginx container (apps/pages/nginx.conf), not into `web`
// (apps/web/Dockerfile only COPYs apps/web/). Fetching it cross-origin from
// :8080 would need CORS headers on the pages origin, which is the one thing
// we were told not to touch (its CSP/headers are the sandbox's other half).
// Embedding it as a build-time import avoids a network round trip, avoids
// touching nginx, and keeps the same "generated, not hand-edited" contract
// manifest.ts already uses.
//
//   node scripts/gen-checks.mjs
import fs from 'fs';

const SRC = 'apps/pages/static/checks.json';
/* The animation probe is a separate script on purpose — folding a metric into
   check.mjs has silently blinded it before — so its numbers land in a separate
   file and are merged here. Without this the review screen cannot show `pre` or
   `zeroSteps`, which is how a teacher sees that a page builds its whole figure
   before step 1 and reveals nothing when stepped through. */
const MOTION = 'apps/pages/static/motion.json';
const OUT = 'apps/web/src/checks.ts';

const rows = JSON.parse(fs.readFileSync(SRC, 'utf8'));
const motion = fs.existsSync(MOTION)
  ? Object.fromEntries(JSON.parse(fs.readFileSync(MOTION, 'utf8')).map((m) => [m.id, m]))
  : {};
for (const r of rows) {
  const m = motion[r.id];
  if (!m || m.broken) continue;
  r.pre = m.pre;                 // strokes already on screen before step 1
  r.zeroSteps = m.zeroSteps;     // steps that reveal nothing
  r.stepCounts = m.stepCounts;   // strokes revealed per step
  r.armed = m.total;
}

fs.writeFileSync(OUT, `// GENERATED by scripts/gen-checks.mjs from ${SRC} — do not edit by hand.
// Rebuild after the checker re-runs:  node scripts/gen-checks.mjs
//
// This is the checker's own output (window.__shellCheck, one row per page),
// verbatim — see packages/kit/checks/check.mjs for how it's produced. The
// review screen (src/pages/Review.tsx) reads it; src/lib/severity.ts turns it
// into worst-first flags.

export interface CheckPerStep {
  n: number;
  labels: number;
  collisions: number;
  pairs: string[];
}

export interface CheckMissingWhy {
  step: number;
  newValues: number[];
  reason: string;
}

export interface CheckExplain {
  steps: number;
  withWhy: number;
  withUses: number;
  hasSetup: boolean;
  groups: number;
  hasSanity: boolean;
  missingWhy: CheckMissingWhy[];
  unverified: unknown[];
}

export interface CheckLatexRepaired {
  escapes: number;
  wrapped: number;
  tags: number;
}

export interface CheckLatex {
  leaked: number;
  samples: string[];
  thaiInMath: number;
  thaiSamples: string[];
  tagFails: unknown[];
  replaced: number;
  badCoord: string[];
  repaired: CheckLatexRepaired;
}

export interface CheckJsxFail {
  type: string;
  msg: string;
}

export interface CheckJsx {
  elements: number;
  constructed: number;
  freePoints: number;
  nanEls: unknown[];
  ownLabels: number;
  tied: number;
  unknown: string[];
  failed: CheckJsxFail[];
  aliased: string[];
  rerouted: string[];
  view3d: boolean;
  offPalette: string[];
  kinds: Record<string, number>;
}

export interface CheckRow {
  id: string;
  errs: string[];
  collapsed: string[];
  N: number;
  per: CheckPerStep[];
  total: number;
  moved: number;
  far: number;
  nlabels: number;
  decrowded: number;
  contrast: string[];
  explain: CheckExplain;
  latex: CheckLatex;
  jsx: CheckJsx | null;
  /* check.mjs writes a SECOND, minimal row for a page that never built — a
     missing lib/, a syntax error, a truncated generation. It carries id, errs,
     N, per and total, nulls for explain/latex/jsx, broken: true, and none of
     the fields above them. The API stores that row verbatim, so the app reads
     it too; severity.ts checks that flag first and reports the build failure
     instead of trying to summarise a report that is not there. Optional
     because the fixture rows this file is generated from never carry it. */
  broken?: boolean;
  // merged from motion.json (the animation probe, a separate script by design)
  pre?: number;
  zeroSteps?: number;
  stepCounts?: number[];
  armed?: number;
}

export const CHECKS: Record<string, CheckRow> = {
${rows.map((r) => `  ${JSON.stringify(r.id)}: ${JSON.stringify(r)},`).join('\n')}
};
`);

console.log(`wrote ${rows.length} rows to ${OUT}`);
