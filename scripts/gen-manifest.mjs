// Rebuild apps/web/src/manifest.ts from whatever pages are actually in
// apps/pages/static/pages. The first version of this file was hand-written for
// 25 fixtures; the fixture set is regenerated whenever the model, the effort or
// the prompt changes, and a hand-written list goes stale silently — it would
// still name pages that no longer exist and miss every new one.
//
//   node scripts/gen-manifest.mjs
import fs from 'fs';
import path from 'path';

const PAGES = 'apps/pages/static/pages';
const OUT = 'apps/web/src/manifest.ts';

const pick = (src, key) => {
  // Shell.page({ title: '...', problem: '...', level: '...' }) — single-quoted,
  // may contain escaped quotes and LaTeX backslashes.
  const m = new RegExp(`${key}\\s*:\\s*'((?:[^'\\\\]|\\\\.)*)'`).exec(src);
  return m ? m[1].replace(/\\'/g, "'").replace(/\\\\/g, '\\') : '';
};

const rows = fs.readdirSync(PAGES)
  .filter(f => f.endsWith('.html'))
  .sort()
  .map(file => {
    const src = fs.readFileSync(path.join(PAGES, file), 'utf8');
    const head = src.slice(0, 4000);
    return {
      file,
      title: pick(head, 'title') || file.replace('.html', ''),
      level: pick(head, 'level'),
    };
  });

const body = rows.map(r =>
  `  { file: ${JSON.stringify(r.file)}, title: ${JSON.stringify(r.title)}, level: ${JSON.stringify(r.level)} },`
).join('\n');

fs.writeFileSync(OUT, `// GENERATED by scripts/gen-manifest.mjs — do not edit by hand.
// Rebuild after changing the fixture set:  node scripts/gen-manifest.mjs
export interface PageEntry {
  file: string;
  title: string;
  level: string;
}

export const PAGES: PageEntry[] = [
${body}
];
`);
console.log(`wrote ${rows.length} entries to ${OUT}`);
console.log(`  without a level: ${rows.filter(r => !r.level).length}`);
console.log(`  falling back to filename: ${rows.filter(r => r.title === r.file.replace('.html','')).length}`);
